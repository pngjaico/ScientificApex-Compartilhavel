from __future__ import annotations

import json
import hashlib
import math
import re
from collections.abc import Mapping
from pathlib import Path
from typing import Any


BENCHMARK_REPORT_PATH = Path("analysis") / "benchmark_report.json"
BENCHMARK_REPORT_CONTRACT = "AgentBenchmarkReport"
BENCHMARK_V2_CONTRACT = "AgentBenchmarkReportV2"
BENCHMARK_VALIDATION_CONTRACT = "AgentBenchmarkValidationReport"
GATE_ELIGIBLE_LEVEL = "acceptance"
REQUIRED_SCORING_DIMENSIONS = (
    "correctness",
    "provenance",
    "reproducibility",
    "safety",
    "usefulness",
)
TRUSTED_EVALUATORS = {"exact-json-v1"}
REQUIRED_ARTIFACTS = ("fixture", "protocol", "output", "gold_answer", "rubric")

_REPORTING_ONLY_LEVELS = {"smoke", "comparative"}
_PLACEHOLDER_VALUES = {
    "-",
    "n/a",
    "na",
    "none",
    "not applicable",
    "not available",
    "null",
    "tbd",
    "todo",
    "unknown",
}
_SHA256 = re.compile(r"^(?:sha256:)?[0-9a-fA-F]{64}$")


def _concrete_text(value: Any, *, minimum_length: int = 1) -> bool:
    if not isinstance(value, str):
        return False
    normalized = value.strip()
    return len(normalized) >= minimum_length and normalized.casefold() not in _PLACEHOLDER_VALUES


def _finite_number(value: Any) -> bool:
    if not isinstance(value, (int, float)) or isinstance(value, bool):
        return False
    try:
        return math.isfinite(float(value))
    except (OverflowError, TypeError, ValueError):
        return False


def _validation_report(
    payload: Mapping[str, Any] | None,
    issues: list[str],
    *,
    source_path: Path | str | None,
    legacy_readable: bool,
) -> dict[str, Any]:
    payload = payload or {}
    eligibility_scope = payload.get("eligibility_scope")
    gate_eligible = not issues and eligibility_scope == "scientific-acceptance"
    cases = payload.get("cases")
    residual_risks = payload.get("residual_risks")
    scoring = payload.get("scoring")
    result: dict[str, Any] = {
        "contract": BENCHMARK_VALIDATION_CONTRACT,
        "status": "pass" if gate_eligible else "block",
        "gate_eligible": gate_eligible,
        "eligibility_scope": eligibility_scope,
        "legacy_readable": legacy_readable,
        "report_contract": payload.get("contract"),
        "benchmark_level": payload.get("level"),
        "reported_status": payload.get("status"),
        "reported_aggregate_status": payload.get("aggregate_status"),
        "declared_gate_eligible": payload.get("gate_eligible"),
        "cases_checked": len(cases) if isinstance(cases, list) else 0,
        "scoring_dimensions_checked": [
            dimension
            for dimension in REQUIRED_SCORING_DIMENSIONS
            if isinstance(scoring, Mapping) and dimension in scoring
        ],
        "scoring": dict(scoring) if isinstance(scoring, Mapping) else {},
        "residual_risk_count": len(residual_risks) if isinstance(residual_risks, list) else 0,
        "issues": issues,
    }
    if source_path is not None:
        result["source_path"] = str(source_path)
    return result


def validate_benchmark_payload(
    payload: Any,
    *,
    source_path: Path | str | None = None,
    _verified_artifacts: bool = False,
) -> dict[str, Any]:
    """Validate the acceptance-level benchmark contract used by machine gates.

    Older JSON objects remain readable and their declared status is reported, but
    only a complete ``AgentBenchmarkReport`` at the ``acceptance`` level can be
    gate eligible.
    """

    if not isinstance(payload, Mapping):
        return _validation_report(
            None,
            ["Benchmark report root must be a JSON object."],
            source_path=source_path,
            legacy_readable=False,
        )

    issues: list[str] = []
    if payload.get("contract") != BENCHMARK_V2_CONTRACT:
        issues.append(f"contract must be '{BENCHMARK_V2_CONTRACT}'; V1 reports are historical only.")

    level = payload.get("level")
    if level != GATE_ELIGIBLE_LEVEL:
        if isinstance(level, str) and level in _REPORTING_ONLY_LEVELS:
            issues.append(
                f"level '{level}' is reporting-only and cannot unlock gates; "
                f"expected '{GATE_ELIGIBLE_LEVEL}'."
            )
        else:
            issues.append(f"level must be '{GATE_ELIGIBLE_LEVEL}'.")

    # Producer-declared status/scores are deliberately not trusted.  V2 reports
    # must be generated by aggregate_benchmark_payload below.
    if payload.get("aggregation") != "recomputed-v2":
        issues.append("aggregation must be 'recomputed-v2'; self-declared reports cannot unlock gates.")
    if not _verified_artifacts:
        issues.append("benchmark payload has no independently verified file-backed evaluation evidence.")
    if payload.get("eligibility_scope") != "scientific-acceptance":
        issues.append("deterministic artifact regression evidence cannot unlock scientific acceptance gates.")

    cases = payload.get("cases")
    if not isinstance(cases, list) or not cases:
        issues.append("cases must be a non-empty array.")
    else:
        seen_case_ids: set[str] = set()
        for index, case in enumerate(cases):
            label = f"cases[{index}]"
            if not isinstance(case, Mapping):
                issues.append(f"{label} must be an object.")
                continue
            case_id = case.get("id")
            if not _concrete_text(case_id):
                issues.append(f"{label}.id must be a non-empty string.")
            elif case_id in seen_case_ids:
                issues.append(f"{label}.id duplicates benchmark case '{case_id}'.")
            else:
                seen_case_ids.add(case_id)
            runs = case.get("runs")
            if not isinstance(runs, list) or not runs:
                issues.append(f"{label}.runs must be a non-empty array with provenance.")
            elif any(not isinstance(run, Mapping) or run.get("status") != "pass" for run in runs):
                issues.append(f"{label}.runs must all pass.")
            if bool(case.get("non_deterministic")) and len(runs) < 3:
                issues.append(f"{label} is non_deterministic and requires three independent runs.")
            if bool(case.get("non_deterministic")) and isinstance(runs, list):
                run_ids = [run.get("run_id") for run in runs if isinstance(run, Mapping)]
                if len(set(run_ids)) != len(runs) or any(not _concrete_text(run_id) for run_id in run_ids):
                    issues.append(f"{label}.runs must have distinct concrete run_id values.")
            for run_index, run in enumerate(runs if isinstance(runs, list) else []):
                if not isinstance(run, Mapping):
                    continue
                hash_fields = ("fixture_hash", "protocol_hash", "output_hash", "gold_answer_hash", "rubric_hash")
                for field in (*hash_fields, "prompt", "model", "reasoning_effort", "duration_seconds", "exit_code"):
                    is_text = field in {*hash_fields, "prompt", "model", "reasoning_effort"}
                    if field not in run or (is_text and not _concrete_text(run[field])):
                        issues.append(f"{label}.runs[{run_index}] is missing concrete '{field}'.")
                    elif field in hash_fields and not _SHA256.fullmatch(run[field].strip()):
                        issues.append(f"{label}.runs[{run_index}].{field} must be a SHA-256 digest.")
                if not _finite_number(run.get("duration_seconds")) or float(run["duration_seconds"]) < 0:
                    issues.append(f"{label}.runs[{run_index}].duration_seconds must be finite and non-negative.")
                if run.get("exit_code") != 0:
                    issues.append(f"{label}.runs[{run_index}].exit_code must be 0.")
                if run.get("evaluator") not in TRUSTED_EVALUATORS:
                    issues.append(f"{label}.runs[{run_index}].evaluator is not a trusted deterministic evaluator.")
                artifacts = run.get("artifacts")
                if not isinstance(artifacts, Mapping) or any(name not in artifacts for name in REQUIRED_ARTIFACTS):
                    issues.append(f"{label}.runs[{run_index}].artifacts must declare fixture, protocol, output, gold_answer, and rubric.")

    provenance = payload.get("provenance")
    if not isinstance(provenance, Mapping):
        issues.append("provenance must be an object.")
    else:
        runtime = provenance.get("runtime")
        if not isinstance(runtime, Mapping):
            issues.append("provenance.runtime must be an object.")
        else:
            if not _concrete_text(runtime.get("model")):
                issues.append("provenance.runtime.model must identify the model.")
            if not _concrete_text(runtime.get("reasoning_effort")):
                issues.append("provenance.runtime.reasoning_effort must identify the reasoning effort.")
        if not _concrete_text(provenance.get("code_revision"), minimum_length=7):
            issues.append("provenance.code_revision must be a concrete revision identifier of at least 7 characters.")
        if not any(
            _concrete_text(provenance.get(field), minimum_length=3)
            for field in ("task_id", "prompt_id", "prompt")
        ):
            issues.append("provenance must include a concrete task_id, prompt_id, or prompt.")

    scoring = payload.get("scoring")
    if not isinstance(scoring, Mapping):
        issues.append("scoring must be an object.")
    else:
        for dimension in REQUIRED_SCORING_DIMENSIONS:
            scorecard = scoring.get(dimension)
            prefix = f"scoring.{dimension}"
            if not isinstance(scorecard, Mapping):
                issues.append(f"{prefix} must be an object with status, score, and threshold.")
                continue
            score = scorecard.get("score")
            threshold = scorecard.get("threshold")
            if not _finite_number(score) or not 0 <= float(score) <= 1:
                issues.append(f"{prefix}.score must be a finite number from 0 to 1.")
            if not _finite_number(threshold) or not 0 < float(threshold) <= 1:
                issues.append(f"{prefix}.threshold must be a finite number greater than 0 and at most 1.")
            if _finite_number(threshold) and float(threshold) > 1:
                issues.append(f"{prefix}.threshold must not exceed 1.")
            if _finite_number(score) and _finite_number(threshold) and float(score) < float(threshold):
                issues.append(f"{prefix}.score must meet or exceed its threshold.")

    residual_risks = payload.get("residual_risks")
    if not isinstance(residual_risks, list) or not residual_risks:
        issues.append("residual_risks must be a non-empty array of concrete risk notes.")
    else:
        for index, risk in enumerate(residual_risks):
            if not _concrete_text(risk, minimum_length=3):
                issues.append(f"residual_risks[{index}] must be a concrete non-placeholder string.")

    return _validation_report(
        payload,
        issues,
        source_path=source_path,
        legacy_readable=True,
    )


def aggregate_benchmark_payload(payload: Mapping[str, Any]) -> dict[str, Any]:
    """Build a V2 report from case runs, ignoring producer aggregate fields."""
    cases = payload.get("cases") if isinstance(payload.get("cases"), list) else []
    dimensions = payload.get("thresholds") if isinstance(payload.get("thresholds"), Mapping) else {}
    scoring: dict[str, dict[str, Any]] = {}
    for dimension in REQUIRED_SCORING_DIMENSIONS:
        values: list[float] = []
        for case in cases:
            if not isinstance(case, Mapping):
                continue
            for run in case.get("runs", []):
                # Producer-supplied scorecards are descriptive only. Scores are
                # populated by _verify_file_backed_payload before aggregation.
                score = run.get("_verified_scores", {}).get(dimension) if isinstance(run, Mapping) and isinstance(run.get("_verified_scores"), Mapping) else None
                if _finite_number(score):
                    values.append(float(score))
        raw_threshold = dimensions.get(dimension, 0.8 if dimension == "usefulness" else 0.9)
        threshold = float(raw_threshold) if _finite_number(raw_threshold) and 0 < float(raw_threshold) <= 1 else (0.8 if dimension == "usefulness" else 0.9)
        score = sum(values) / len(values) if values else 0.0
        scoring[dimension] = {"score": score, "threshold": threshold, "status": "pass" if score >= threshold else "block"}
    result = dict(payload)
    result.update({
        "contract": BENCHMARK_V2_CONTRACT,
        "contract_version": 2,
        "level": GATE_ELIGIBLE_LEVEL,
        "aggregation": "recomputed-v2",
        "eligibility_scope": "deterministic-artifact-regression",
        "scoring": scoring,
        "status": "pass" if all(item["status"] == "pass" for item in scoring.values()) else "block",
        "aggregate_status": "pass" if all(item["status"] == "pass" for item in scoring.values()) else "block",
        "gate_eligible": False,  # validation is authoritative and overwrites this view.
    })
    return result


def validate_benchmark_file(report_path: Path) -> dict[str, Any]:
    report_path = Path(report_path)
    if not report_path.exists():
        return _validation_report(
            None,
            [f"Benchmark report is missing: {report_path}."],
            source_path=report_path,
            legacy_readable=False,
        )
    try:
        payload = json.loads(report_path.read_text(encoding="utf-8-sig"))
    except (OSError, UnicodeError, json.JSONDecodeError, RecursionError) as exc:
        return _validation_report(
            None,
            [f"Benchmark report is not readable valid JSON: {exc}."],
            source_path=report_path,
            legacy_readable=False,
        )
    if not isinstance(payload, Mapping):
        return validate_benchmark_payload(payload, source_path=report_path)
    verified = _verify_file_backed_payload(payload, report_path.parent)
    if isinstance(verified, dict):
        payload = aggregate_benchmark_payload(verified)
    return validate_benchmark_payload(payload, source_path=report_path, _verified_artifacts=isinstance(verified, dict))


def _verify_file_backed_payload(payload: Mapping[str, Any], base_dir: Path) -> dict[str, Any] | None:
    """Verify declared artifacts and derive only deterministic evaluator scores.

    Paths are relative to the report directory and may not escape it. The
    exact-json evaluator compares parsed output and gold-answer values; producer
    score fields are ignored. Other dimensions require explicit rubric boolean
    assertions and otherwise receive zero, keeping subjective cases blocked.
    """
    result = dict(payload)
    if payload.get("contract") != BENCHMARK_V2_CONTRACT or not isinstance(payload.get("cases"), list) or not payload.get("cases"):
        return None
    verified_cases: list[dict[str, Any]] = []
    try:
        for case in payload.get("cases", []):
            if not isinstance(case, Mapping) or not isinstance(case.get("runs"), list):
                return None
            verified_case = dict(case)
            runs = []
            for original in case["runs"]:
                if not isinstance(original, Mapping) or original.get("evaluator") not in TRUSTED_EVALUATORS:
                    return None
                run = dict(original)
                artifacts = run.get("artifacts")
                if not isinstance(artifacts, Mapping):
                    return None
                contents: dict[str, bytes] = {}
                for name in REQUIRED_ARTIFACTS:
                    ref = artifacts.get(name)
                    if not isinstance(ref, Mapping) or not _concrete_text(ref.get("path")) or not _SHA256.fullmatch(str(ref.get("sha256", ""))):
                        return None
                    candidate = (base_dir / ref["path"]).resolve()
                    if not candidate.is_relative_to(base_dir.resolve()) or not candidate.is_file():
                        return None
                    content = candidate.read_bytes()
                    actual = hashlib.sha256(content).hexdigest()
                    if actual.casefold() != ref["sha256"].removeprefix("sha256:").casefold():
                        return None
                    contents[name] = content
                for field, artifact_name in (
                    ("fixture_hash", "fixture"), ("protocol_hash", "protocol"),
                    ("output_hash", "output"), ("gold_answer_hash", "gold_answer"),
                    ("rubric_hash", "rubric"),
                ):
                    actual = hashlib.sha256(contents[artifact_name]).hexdigest()
                    if run.get(field, "").removeprefix("sha256:").casefold() != actual.casefold():
                        return None
                try:
                    json.loads(contents["fixture"])
                    json.loads(contents["protocol"])
                    output = json.loads(contents["output"])
                    gold = json.loads(contents["gold_answer"])
                    rubric = json.loads(contents["rubric"])
                except (UnicodeError, json.JSONDecodeError):
                    return None
                scores = {"correctness": 1.0 if output == gold else 0.0}
                # Artifact integrity establishes narrow provenance; reproducibility
                # needs independent runs. Exact-json cannot assess scientific
                # safety/usefulness, and rubric booleans are not accepted as proof.
                scores.update({
                    "provenance": 1.0,
                    "reproducibility": 0.0,
                    "safety": 0.0,
                    "usefulness": 0.0,
                })
                run["_verified_scores"] = scores
                runs.append(run)
            run_ids = [run.get("run_id") for run in runs]
            output_hashes = [run.get("output_hash") for run in runs]
            reproducible = (
                len(runs) >= 2
                and all(_concrete_text(run_id) for run_id in run_ids)
                and len(set(run_ids)) == len(run_ids)
                and len(set(output_hashes)) == 1
            )
            for run in runs:
                run["_verified_scores"]["reproducibility"] = 1.0 if reproducible else 0.0
            verified_case["runs"] = runs
            verified_cases.append(verified_case)
    except (OSError, ValueError, TypeError):
        return None
    result["cases"] = verified_cases
    return result


def validate_benchmark_report(project_dir: Path) -> dict[str, Any]:
    return validate_benchmark_file(Path(project_dir) / BENCHMARK_REPORT_PATH)


def benchmark_gate_passed(project_dir: Path) -> bool:
    validation = validate_benchmark_report(project_dir)
    return (
        validation.get("gate_eligible") is True
        and validation.get("eligibility_scope") == "scientific-acceptance"
    )
